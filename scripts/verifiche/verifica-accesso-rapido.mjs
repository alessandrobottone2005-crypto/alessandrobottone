// Avvio leggero, cronologia e sospensione della scena. Chrome locale; nessuna pubblicazione.
import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { apriChrome, attesa } from '../lib/chrome.mjs'
const base = process.argv[2] ?? 'http://127.0.0.1:4173/'
const out = join(import.meta.dirname, '../../verifiche/risultati/accesso-rapido')
mkdirSync(out, { recursive: true })
const risultati = []
for (const caso of [{ nome:'desktop' }, { nome:'telefono', telefono:true, cpu:1 }, { nome:'tablet', width:820, height:1180, ridotto:true }, { nome:'senza-webgl', senzaWebGL:true, ridotto:true }].filter(c=>!process.env.CASO || process.env.CASO===c.nome)) {
 const b = await apriChrome(caso)
 const check = async (expression, label) => assert.ok(await b.valuta(expression), `${caso.nome}: ${label}`)
 const nav = async (text) => b.valuta(`(()=>{const el=[...document.querySelectorAll('.navigazione-sezioni button')].find(b=>b.textContent.includes(${JSON.stringify(text)})); el.focus();el.click()})()`)
 const foto = async (name) => writeFileSync(join(out,caso.nome+'-'+name+'.png'),Buffer.from((await b.cmd('Page.captureScreenshot')).data,'base64'))
 try {
  await b.cmd('Page.addScriptToEvaluateOnNewDocument', {source:`window.__draws=0; for(const C of [WebGLRenderingContext,WebGL2RenderingContext]) for(const k of ['drawArrays','drawElements','drawArraysInstanced','drawElementsInstanced']){const f=C.prototype[k];if(f)C.prototype[k]=function(...a){window.__draws++;return f.apply(this,a)}}`})
  await b.cmd('Page.navigate',{url:base})
  await b.aspetta(`!!document.querySelector('[data-ingresso-progetti]')`)
  await attesa(700)
  await check(`!document.querySelector('canvas')`,'ingresso senza canvas')
  await check(`document.querySelector('.ingresso-rapido').scrollWidth <= innerWidth`,'ingresso senza overflow')
  await foto('ingresso')
  await b.valuta(`document.querySelector('[data-ingresso-progetti]').focus()`)
  await b.cmd('Input.dispatchKeyEvent',{type:'keyDown',key:'Enter',code:'Enter',windowsVirtualKeyCode:13,text:'\r'})
  await b.cmd('Input.dispatchKeyEvent',{type:'keyUp',key:'Enter',code:'Enter',windowsVirtualKeyCode:13})
  await b.aspetta(`document.querySelectorAll('[data-progetto]').length===9`)
  await attesa(1000)
  const richieste = await b.valuta(`performance.getEntriesByType('resource').map(r=>({url:r.name,bytes:r.transferSize}))`)
  assert.ok(!richieste.some(r=>/Volto3D|Nome3D|\/sala\/|\/computer\/|logo-metallo|musica\./.test(r.url)), 'nessuna risorsa dell’esperienza dal percorso rapido')
  await b.valuta('history.back()')
  await b.aspetta(`document.activeElement.matches('[data-ingresso-progetti]')`)
  await b.valuta('history.forward()')
  await b.aspetta(`!!document.querySelector('dialog.archivio[open]')`)
  await b.valuta(`document.querySelector('[data-progetto="inktober"]').click()`)
  await b.aspetta(`!!document.querySelector('.archivio-contatti')`)
  await b.aspetta(`document.querySelectorAll('.archivio-blocchi img').length===5`)
  await b.valuta(`document.querySelectorAll('.archivio-progetto img').forEach(i=>i.loading='eager')`)
  await b.aspetta(`[...document.querySelectorAll('.archivio-progetto img')].every(i=>i.complete && i.naturalWidth)` )
  await b.valuta(`document.querySelector('.archivio-contatti').scrollIntoView({block:'end'})`)
  await attesa(700)
  const posizione = await b.valuta(`document.querySelector('.archivio-scroll').scrollTop`)
  await b.clic('.archivio-contatti button')
  await b.aspetta(`location.hash==='#contatti' && document.activeElement.id==='contatti'`,60000)
  await check(`!document.querySelector('dialog.archivio[open]') && !document.documentElement.classList.contains('scroll-fermo')`,'contatti visibili e scroll libero')
  await check(`!!document.querySelector('[aria-label="attiva audio"]')`,'contatti da archivio senza audio automatico')
  await b.valuta('history.back()')
  await b.aspetta(`!!document.querySelector('.archivio-contatti') && Math.abs(document.querySelector('.archivio-scroll').scrollTop-${posizione})<3`,30000)
  await b.aspetta(`!!document.activeElement.closest('.archivio-contatti')`)
  await b.clic('[aria-label="torna al computer"]')
  await b.aspetta(`!!document.querySelector('.mac-schermo[data-fase="acceso"]:not([inert])')`,40000)
  // Canvas della home conservati, senza disegni mentre l’archivio li copre.
  await attesa(1200)
  await b.valuta(`void(window.__canvases=[...document.querySelectorAll('canvas')])`)
  const y = await b.valuta('scrollY')
  await nav('progetti')
  await b.aspetta(`!!document.querySelector('dialog.archivio[open]')`)
  await attesa(600)
  const d = await b.valuta('window.__draws')
  await attesa(2000)
  const disegni = await b.valuta(`window.__draws-${d}`)
  assert.equal(disegni,0,'canvas della scena fermi sotto archivio')
  await b.valuta('history.back()')
  await b.aspetta(`!document.querySelector('dialog.archivio[open]')`)
  await check(`Math.abs(scrollY-${y})<3`,'cronologia conserva posizione home')
  await check(`window.__canvases.every(c=>c.isConnected)`,'canvas conservati')
  await check(`document.activeElement.textContent.includes('progetti')`,'focus restituito alla navigazione')
  // Collegamento diretto, senza la scena anche dopo reload.
  await b.cmd('Page.navigate',{url:base+'progetti/cuphead-mugman-art-toys'})
  await b.aspetta(`!!document.querySelector('[data-blocco="modello3d"]')`)
  await check(`document.querySelector('[data-blocco]').dataset.blocco==='modello3d'`,'modello prima del PDF')
  await b.cmd('Page.reload')
  await b.aspetta(`!!document.querySelector('[data-blocco="modello3d"]')`)
  await check(`!document.querySelector('[data-logo-continuo]')`,'ricarica progetto senza esperienza')
  const pdfVicino = await b.valuta(`(() => { const p=document.querySelector('[data-blocco=pdf]'),r=document.querySelector('.archivio-scroll');return p.getBoundingClientRect().top<=r.getBoundingClientRect().bottom+r.clientHeight})()`)
  if (!pdfVicino) await check(`!document.querySelector('.pdf-documento')`,'lettore PDF lontano non montato')
  await b.valuta(`document.querySelector('[data-blocco=pdf]').scrollIntoView({block:'start'})`)
  await b.aspetta(`document.querySelectorAll('[data-pdf-pagina]').length>0`,60000)
  await b.valuta(`document.querySelector('.archivio-contatti').scrollIntoView({block:'end'})`)
  await attesa(500)
  const fondoPdf=await b.valuta(`document.querySelector('.archivio-scroll').scrollTop`)
  await b.clic('.archivio-contatti button')
  await b.aspetta(`document.activeElement.id==='contatti'`,60000)
  await b.valuta('history.back()')
  await b.aspetta(`!!document.querySelector('.archivio-contatti') && Math.abs(document.querySelector('.archivio-scroll').scrollTop-${fondoPdf})<3`,60000)
  assert.deepEqual(b.errori,[],'nessun errore runtime')
  risultati.push({caso:caso.nome,esito:'ok',disegniScenaInArchivio:disegni,richiestePercorsoRapido:richieste.length,bytePercorsoRapido:richieste.reduce((s,r)=>s+r.bytes,0)})
  writeFileSync(join(out,'risultati.json'),JSON.stringify(risultati,null,2))
  console.log(caso.nome,'ok')
 } catch(e) { await foto('errore'); console.error(await b.valuta(`({url:location.href,focus:document.activeElement?.outerHTML?.slice(0,400),scroll:document.querySelector('.archivio-scroll')?.scrollTop,errori:document.body.innerText.slice(-600)})`));throw e }
 finally { await b.chiudi() }
}
writeFileSync(join(out,'risultati.json'),JSON.stringify(risultati,null,2))
// I campioni prima/dopo sono raccolti a freddo separatamente per non inquinare la misura.
if(process.env.PRIMA && process.env.DOPO) writeFileSync(join(out,'confronto.json'),JSON.stringify({prima:JSON.parse(readFileSync(process.env.PRIMA)),dopo:JSON.parse(readFileSync(process.env.DOPO))},null,2))
